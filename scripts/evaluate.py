"""Evaluate the dashboard pipeline against held-out truth, injected data problems and runtime.

Usage: python scripts/evaluate.py [--seeds 20]     Author: Rayyan Anwar
"""
import argparse
import json
import platform
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.business import CANDIDATES, analyse_series, analyse_table, load_table, regularise  # noqa: E402
from app.models import FORECASTERS, ModelUnavailable  # noqa: E402
from app.sample import generate_sales  # noqa: E402

H = 28


def holdout(seeds: int) -> dict:
    ratio, cover, regret, near_best, picks, gains = [], [], [], [], {}, []
    for s in range(seeds):
        raw = generate_sales(s, 730 + H)
        df, _ = load_table(raw.to_csv(index=False))
        for name in sorted(df["series"].unique()):
            full, _ = regularise(df[df["series"] == name], "D", "sum", "zero")
            train, truth = full.iloc[:-H], full.to_numpy()[-H:]
            r = analyse_series(train, "D", H)
            fc = np.array(r["forecast"]["values"])
            lo, hi = np.array(r["forecast"]["lower"]), np.array(r["forecast"]["upper"])
            mae = float(np.abs(fc - truth).mean())
            sn = float(np.abs(FORECASTERS["seasonal_naive"](train.to_numpy(), H, 7) - truth).mean())
            ratio.append(mae / sn)
            cover.append(float(((truth >= lo) & (truth <= hi)).mean()))
            cand = {}
            for c in CANDIDATES:
                try:
                    cand[c] = float(np.abs(FORECASTERS[c](train.to_numpy(), H, 7) - truth).mean())
                except ModelUnavailable:
                    pass
            best = min(cand.values())
            regret.append(100 * (mae / best - 1))
            near_best.append(mae <= 1.05 * best)
            picks[r["model"]] = picks.get(r["model"], 0) + 1
            gains.append(r["backtest"]["improvement_over_reference_pct"])
    return {"forecasts": len(ratio), "mae_ratio_vs_seasonal_naive_mean": float(np.mean(ratio)), "mae_ratio_vs_seasonal_naive_median": float(np.median(ratio)),
            "share_beating_seasonal_naive": float(np.mean(np.array(ratio) < 1)), "interval80_empirical_coverage": float(np.mean(cover)),
            "selection_regret_pct_mean": float(np.mean(regret)), "share_within_5pct_of_hindsight_best": float(np.mean(near_best)),
            "models_chosen": picks, "mean_backtest_improvement_claimed_pct": float(np.mean(gains))}


def data_quality() -> dict:
    raw = generate_sales(7, 400)
    bad_dates = raw.sample(50, random_state=1).index
    bad_vals = raw.drop(bad_dates).sample(40, random_state=2).index
    raw = raw.copy()
    raw["date"] = raw["date"].astype(object)
    raw["value"] = raw["value"].astype(object)
    raw.loc[bad_dates, "date"] = "not-a-date"
    raw.loc[bad_vals, "value"] = "n/a"
    df, rep = load_table(raw)
    expected = {"invalid_date": 50, "invalid_value": 40}
    one = df[df["series"] == "mugs"]
    s, prep = regularise(one, "D", "sum", "zero")
    days_with_rows = one["date"].dt.normalize().nunique()
    return {"injected": expected, "reported": rep["dropped"], "counts_exact": rep["dropped"] == expected,
            "missing_periods_reported": prep["periods_without_data_filled"], "missing_periods_independent_count": int(len(s) - days_with_rows),
            "fill_count_exact": prep["periods_without_data_filled"] == len(s) - days_with_rows}


def runtime() -> dict:
    parts = []
    for i in range(20):
        d = generate_sales(i, 730)
        d = d[d["series"] == "coffee_beans"].copy()
        d["series"] = f"item_{i:02d}"
        parts.append(d)
    big = pd.concat(parts, ignore_index=True)
    t0 = time.perf_counter()
    df, rep = load_table(big.to_csv(index=False))
    r = analyse_table(df, rep, horizon=28)
    return {"series": len(r["series"]), "periods_each": 730, "seconds_total": time.perf_counter() - t0}


def to_md(r):
    h, q, rt, e = r["holdout"], r["data_quality"], r["runtime"], r["environment"]
    return "\n".join([
        "# Results (generated by `scripts/evaluate.py`)", "",
        f"- Created (UTC): {r['created_utc']}; {e['platform']}; Python {e['python']}; NumPy {e['numpy']}; CPUs {e['cpu_count']}", "",
        f"## Held-out accuracy ({r['seeds']} seeded sales datasets x 3 products = {h['forecasts']} forecasts; train on 730 days, forecast the next {H})", "",
        "| Measure | Value |", "|---|---:|",
        f"| MAE vs seasonal naive on held-out days (mean / median ratio) | {h['mae_ratio_vs_seasonal_naive_mean']:.2f} / {h['mae_ratio_vs_seasonal_naive_median']:.2f} |",
        f"| Share of forecasts better than seasonal naive | {h['share_beating_seasonal_naive']:.2f} |",
        f"| 80% interval empirical coverage on held-out days | {h['interval80_empirical_coverage']:.2f} |",
        f"| Selection regret vs hindsight-best candidate (mean) | {h['selection_regret_pct_mean']:.1f}% |",
        f"| Chosen model within 5% of hindsight best | {h['share_within_5pct_of_hindsight_best']:.2f} |",
        f"| Mean backtest improvement the app reports vs reference | {h['mean_backtest_improvement_claimed_pct']:.1f}% |",
        f"| Models chosen | {h['models_chosen']} |", "",
        "## Data-quality handling (injected problems)", "",
        f"Injected {q['injected']}; reported {q['reported']}; exact: {q['counts_exact']}. Empty periods filled: reported {q['missing_periods_reported']} vs independent count {q['missing_periods_independent_count']}; exact: {q['fill_count_exact']}.", "",
        "## Runtime", "", f"{rt['series']} series x {rt['periods_each']} daily periods, load + validate + backtest + forecast: {rt['seconds_total']:.1f} s (1-core sandbox).", "",
        "Caveats: synthetic sales with smooth planted structure and one spike per product; 80% intervals are approximate; held-out windows are correlated within a series, so coverage has wide uncertainty; none of this predicts accuracy on real business data."]) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=20)
    a = ap.parse_args()
    r = {"created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"), "seeds": a.seeds,
         "environment": {"platform": platform.platform(), "python": sys.version.split()[0], "numpy": np.__version__, "cpu_count": __import__("os").cpu_count()},
         "holdout": holdout(a.seeds), "data_quality": data_quality(), "runtime": runtime()}
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "results.json").write_text(json.dumps(r, indent=2))
    (ROOT / "results" / "RESULTS.md").write_text(to_md(r))
    print(to_md(r))


if __name__ == "__main__":
    main()
